//
// WHY A CATALOG AND NOT LITERALS
// The rule is: fixed copy goes through i18n; where it cannot, English. What used to be here was 172
// hardcoded Portuguese strings spread across the core, the editor and the panel — and the core is a
// PURE module that has no business owning prose. So the core returns ids (`reason.noOptions`) and the
// words live here.
//
// WHAT IS *NOT* HERE, on purpose: `throw` messages and `console.*`. Those are developer diagnostics,
// they never reach the panel, and they are written in English.
//
// The catalogs are checked by the COMPILER: `message_en` is typed as `typeof message_pt`, so a missing
// or misspelled key is a build error, not a blank label at runtime.

