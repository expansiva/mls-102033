export type StudioMessageId = keyof typeof message_pt;

const CATALOGS: Record<string, typeof message_pt> = { pt: message_pt, en: message_en };

/**
 * The catalog for the document's language, resolved by the RUNTIME's own rule (exact locale, then the
 * primary subtag, then the first declared) — the same one the pages and the header use, so
 * `Ctrl+Alt+L` switches the panel along with everything else.
 */
function catalog(): typeof message_pt {
  const lang = typeof document === 'undefined' ? 'en' : (document.documentElement?.lang || 'en');
  const key = getRuntimeLanguage(Object.keys(CATALOGS), lang) ?? 'en';
  return CATALOGS[key] ?? message_en;
}

/**
 * The text for an id, with `{param}` filled in.
 *
 * An unknown id comes back as the id itself: a visible `panel.whatever` in the UI is a bug report,
 * where an empty string would just look like a rendering glitch.
 */
export function t(id: string, params?: Record<string, string | number>): string {
  const text = (catalog() as Record<string, string>)[id];
  if (text === undefined) return id;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/gu, (whole, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole
  ));
}

/** Same, for a reference the core produced. */
export function tr(ref: IMessageRef | undefined): string {
  return ref ? t(ref.id, ref.params) : '';
}

/** Ids the catalog knows — the completeness guard uses it. */
export function messageIds(): string[] {
  return Object.keys(message_pt);
}
